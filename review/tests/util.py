#: The evaluation-scope grammar, and the AUTHORITY it is closed against.
#:
#: Round-3 F1 was the third finding on this one anchor: round 1 put
#: definition-time expressions in the defining scope, round 2 gave deferred
#: bodies their own, and round 3 found PEP 695 type parameters — dropped
#: entirely — and lazy type aliases attributed to `<module>`. Three
#: instances of one shape, which is the hunting signature the
#: boundary-authority terminator exists to end: the domain "every execution
#: container" was closed against nothing but the visitor methods someone
#: had written.
#:
#: So the domain is now declared closed RELATIVE TO A STATED AUTHORITY: the
#: `ast` grammar of the running interpreter — generated by CPython, not by
#: this repository, and gated by
#: `test_the_scope_grammar_covers_the_ast_grammar`. Every concrete node
#: type is classified exactly once, and for a scope-introducing node EVERY
#: field is routed by name. A node type or field the grammar grows — a
#: future interpreter's new lazy scope — fails that gate until someone
#: decides it, instead of being swept up by a generic traversal. There are
#: no prefix rules and no default arm; that absence IS the fix.
#:
#: Treatments:
#:   skip                a name or flag, not an evaluable child
#:   current             evaluates in the scope now on the stack
#:   own_scope           the function's own body (pushes the function name)
#:   lambda_scope        deferred, unnamed: `<lambda>`
#:   genexp_elt          deferred until a consumer iterates: `<genexpr>`
#:   genexp_generators   outermost iterable eager in the creating scope,
#:                       every other iterable, target and filter deferred
#:   annotation          a PEP 695 lazy scope: `<annotation>`, ALWAYS —
#:                       `from __future__ import annotations` governs legacy
#:                       annotations and has no bearing on these
#:   legacy_annotation   `<annotation>`, unless the module stringifies
SCOPE_RULES = {
    "FunctionDef": {"name": "skip", "type_comment": "skip",
                    "decorator_list": "current", "args": "current",
                    "type_params": "current",
                    "returns": "legacy_annotation", "body": "own_scope"},
    "AsyncFunctionDef": {"name": "skip", "type_comment": "skip",
                         "decorator_list": "current", "args": "current",
                         "type_params": "current",
                         "returns": "legacy_annotation",
                         "body": "own_scope"},
    "Lambda": {"args": "current", "body": "lambda_scope"},
    "GeneratorExp": {"elt": "genexp_elt",
                     "generators": "genexp_generators"},
    # A class body EXECUTES at the class statement, so it is the current
    # scope; only its type parameters are lazy.
    "ClassDef": {"name": "skip", "bases": "current", "keywords": "current",
                 "decorator_list": "current", "type_params": "current",
                 "body": "current"},
    "TypeAlias": {"name": "current", "type_params": "current",
                  "value": "annotation"},
    "TypeVar": {"name": "skip", "bound": "annotation",
                "default_value": "annotation"},
    "ParamSpec": {"name": "skip", "default_value": "annotation"},
    "TypeVarTuple": {"name": "skip", "default_value": "annotation"},
    "AnnAssign": {"target": "current", "annotation": "legacy_annotation",
                  "value": "current", "simple": "skip"},
    "arg": {"arg": "skip", "annotation": "legacy_annotation",
            "type_comment": "skip"},
}

#: Every other concrete node type: its children evaluate in the scope now
#: on the stack. Enumerated, never defaulted — a new node type is
#: unclassified until someone rules on it. `arguments` and `comprehension`
#: are here on purpose: their evaluable children are defaults and iterables
#: that run where they are written, while the parts that are NOT
#: (`arg` annotations, a generator's deferred iterables) are routed by the
#: rules above.
